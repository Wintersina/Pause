    public const uint Seed = 1;
    public const float BudgetFactor = 1.15f;
    public const float Slack = .02f;        // absolute, on top of the factor: Monte Carlo noise at 2000 rolls (one standard error is <= 1.1 points)
    public const float MinAttackedShare = .5f;   // an attack that shows itself in under half the rolls is not measured, it is broken


    static void Catalogue()
    {
        var missing = new List<string>();
        int n = 0;
        foreach (var id in AttackBudgetScenarios.AllIds())
        {
            n++;
            if (!Pinned.ContainsKey(id) && !Themed.ContainsKey(id)) missing.Add(id);
        }
        Check("every roster attacker, mine, elite and boss attack has a pinned baseline or a Themed row (" + n + " attacks; unpinned: " +
              string.Join(", ", missing) + ")", missing.Count == 0 && n >= 40);
        var stale = new List<string>();
        var live = new HashSet<string>(AttackBudgetScenarios.AllIds());
        foreach (var k in Pinned.Keys) if (!live.Contains(k) && !Themed.ContainsValue(k)) stale.Add(k);
        Check("every pin still names an attack in the game, or one a Themed row replaced (stale: " + string.Join(", ", stale) + ")", stale.Count == 0);
    }

    static void SpotChecksHold()
    {
        foreach (var id in SpotChecks)
        {
            Pin p;
            if (!Pinned.TryGetValue(id, out p)) { Check(id + ": pinned", false); continue; }
            var r = Measure(id);
            // (a few rolls can differ run to run: the world's clock and the brains' drift directions carry a little state between
            // attacks in one editor process; within a point and a half is the same measurement)
            int tol = Mathf.CeilToInt(Rolls * .015f);
            Check(id + ": today's attack still measures its pin (" + r.hits + "/" + r.attacked + " ghost " + r.ghostHits + " vs " + p.hits + "/" + p.attacked + " ghost " + p.ghost + ", tolerance " + tol + ")",
                  Mathf.Abs(r.hits - p.hits) <= tol && Mathf.Abs(r.attacked - p.attacked) <= tol && Mathf.Abs(r.ghostHits - p.ghost) <= tol);
        }
    }

    static void ThemedRowsPass()
    {
        foreach (var kv in Themed)
        {
            var r = Measure(kv.Key);
            string why;
            bool ok = WithinBudget(kv.Key, r, out why);
            Check("themed attack within the budget: " + why, ok);
        }
    }

    // ---- the sweep: measure everything, print the table ---------------------------------

    // -executeMethod AttackBudgetTest.Sweep [-rolls N] [-only substring]
    // -executeMethod AttackBudgetTest.SweepThemed [-rolls N] [-only substring] [-trace]: the same for the themed fixtures (they are not
    // attacks of the game, so Sweep does not list them): hit rate, standing-still rate and the budget verdict against the pinned attack.
    public static void SweepThemed()
    {
        fails = 0;
        int rolls = Rolls;
        string only = null;
        var args = System.Environment.GetCommandLineArgs();
        for (int i = 0; i < args.Length - 1; i++)
        {
            if (args[i] == "-rolls") int.TryParse(args[i + 1], out rolls);
            if (args[i] == "-only") only = args[i + 1];
        }
        for (int i = 0; i < args.Length; i++) if (args[i] == "-trace") DodgeBot.Trace = true;
        try
        {
            foreach (var kv in Themed)
            {
                if (only != null && !kv.Key.Contains(only)) continue;
                var r = Measure(kv.Key, rolls);
                string why;
                bool ok = WithinBudget(kv.Key, r, out why);
                Debug.Log("[ATKBUD] THEMED " + (ok ? "ok   " : "OVER ") + kv.Key + ": bot " + r.HitRate.ToString("P1") + " (" + r.hits + "/" + r.attacked + "), standing still " + r.GhostRate.ToString("P1") +
                          ", shown in " + r.attacked + "/" + r.rolls + "; " + AttackBudgetScenarios.Shape(kv.Key) + " -- " + why);
            }
        }
        finally { AttackBudgetScenarios.Cleanup(); }
        TestHarness.Exit(0);
    }

    public static void Sweep()
    {
        fails = 0;
        int rolls = Rolls;
        string only = null;
        var args = System.Environment.GetCommandLineArgs();
        for (int i = 0; i < args.Length - 1; i++)
        {
            if (args[i] == "-rolls") int.TryParse(args[i + 1], out rolls);
            if (args[i] == "-only") only = args[i + 1];
        }
        for (int i = 0; i < args.Length; i++) if (args[i] == "-trace") DodgeBot.Trace = true;
        var sw = Stopwatch.StartNew();
        var sb = new StringBuilder();
        int bad = 0;
        try
        {
            foreach (var id in AttackBudgetScenarios.AllIds())
            {
                if (only != null && !id.Contains(only)) continue;
                var t = Stopwatch.StartNew();
                var r = Measure(id, rolls);
                string line = "        { \"" + id + "\", new Pin(" + r.hits + ", " + r.attacked + ", " + r.ghostHits + ") },   // " +
                              r.HitRate.ToString("P1") + " bot, " + r.GhostRate.ToString("P1") + " standing; shown in " + r.attacked + "/" + r.rolls +
                              "; " + AttackBudgetScenarios.Shape(id);
                if (r.AttackedShare < MinAttackedShare) { line += "  <-- SHOWS ITSELF IN UNDER HALF THE ROLLS"; bad++; }
                Debug.Log("[ATKBUD] PIN " + line.Trim() + "  (" + t.Elapsed.TotalSeconds.ToString("0.0") + " s)");
                sb.AppendLine(line);
            }
        }
        finally { AttackBudgetScenarios.Cleanup(); }
        Debug.Log("[ATKBUD] sweep done in " + sw.Elapsed.TotalSeconds.ToString("0") + " s; attacks that barely show: " + bad);
        TestHarness.Exit(0);
    }

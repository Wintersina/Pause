    public static int Execute()
    {
        fails = 0;
        using (new TestHarness.Sandbox())
        {
            try
            {
                Harness();
                Catalogue();
                SpotChecksHold();
                ThemedRowsPass();
            }
            finally { AttackBudgetScenarios.Cleanup(); }
        }
        Debug.Log("[ATKBUD] failures: " + fails);
        return fails;
    }

    static void Harness()
    {
        // 1. deterministic: the same attack twice, the same numbers
        var a = Measure("roster:space_fighter_4", 60);
        var b = Measure("roster:space_fighter_4", 60);
        Check("the harness is deterministic (" + a.hits + "/" + a.attacked + " twice: " + b.hits + "/" + b.attacked + ")",
              a.hits == b.hits && a.attacked == b.attacked && a.ghostHits == b.ghostHits && a.attacked > 0);
        // 2. the bot dodges: against a ghost that stands still, an aimed attack hits far more often
        Check("the bot beats a ghost that never moves (bot " + a.hits + " vs ghost " + a.ghostHits + " of " + a.attacked + ")",
              a.ghostHits >= 10 && a.hits < a.ghostHits);
        // 3. nothing to dodge, nothing hit: a rock never attacks, so the bot is never hit and the attack never shows
        var rock = new Quiet();
        AttackBudgetScenarios.Reset();
        var q = DodgeBot.Run(rock, 20, Seed);
        Check("a hazard-free world scores no hits and no attacks (" + q.hits + "/" + q.attacked + ")", q.hits == 0 && q.attacked == 0 && q.ghostHits == 0);
        // 4. a hazard that cannot be avoided is scored: a wall across the lane the bot cannot leave
        var wall = new Wall();
        var w = DodgeBot.Run(wall, 20, Seed);
        Check("an unavoidable hazard scores a hit in every roll (" + w.hits + "/" + w.attacked + ")", w.attacked == 20 && w.hits == 20);
        AttackBudgetScenarios.Cleanup();
    }


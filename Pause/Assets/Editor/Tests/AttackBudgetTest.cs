// THE ATTACK BUDGET (docs/world-attacks-design.md FR6, implementation plan 0a).
//
// "Themed attacks replace attacks; they must not be harder." The dodge bot
// (DodgeBot: reaction .25 s, the ship's speed, aim locked at the tell) is
// rolled Rolls times per attack against the real game code
// (AttackBudgetScenarios) and its hit rate is PINNED here for every roster
// attacker, rail mine, elite and boss attack as it stood BEFORE any world got
// themed attacks. A themed attack that replaces an old one is measured the same
// way (same seed, so the same start positions) and must satisfy
//
//     rate(new) <= rate(old) * BudgetFactor + Slack
//
// (Slack: the rates are Monte Carlo over Rolls rolls; a 1-in-Rolls hit is noise.)
//
//   Pinned           id -> bot hits / rolls the attack showed itself in / the
//                    stand-still ghost's hits (information)
//   Themed           id of a new attack -> the id of the old attack it replaces
//                    (later phases add rows; AttackBudgetTest then checks them)
//   WithinBudget     the check, for any measured Result
//   Execute          harness sanity (deterministic, the bot beats a ghost, no
//                    hazards means no hits), spot checks of pinned entries, the
//                    catalogue is fully pinned or themed, every Themed row passes
//   Sweep            -executeMethod AttackBudgetTest.Sweep: measures EVERY
//                    attack and prints the pin table (PIN lines) to paste above
//
// Run: scripts/unity-batch.sh -executeMethod AllTests.RunSuites -suites AttackBudgetTest

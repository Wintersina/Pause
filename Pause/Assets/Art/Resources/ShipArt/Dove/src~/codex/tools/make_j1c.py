def apply_layer(base, draw_damage):
    layer = Image.new("RGBA", base.size, (0, 0, 0, 0))
    draw_damage(layer)
    composited = Image.alpha_composite(base.convert("RGBA"), layer).convert("RGB")
    green = Image.new("L", base.size, 0)
    green_data = []
    for pixel in base.convert("RGB").getdata():
        green_data.append(0 if pixel == (0, 255, 0) else 255)
    green.putdata(green_data)
    # This final mask guarantees that no damage pixel can change the green field.
    return Image.composite(composited, base, green)


def save_preview(base, state1, state2):
    canvas = Image.new("RGB", (3072, 1024), (11, 11, 26))
    for index, image in enumerate((base, state1, state2)):
        cut = image.convert("RGB").copy()
        px = cut.load()
        for y in range(cut.height):
            for x in range(cut.width):
                if px[x, y] == (0, 255, 0):
                    px[x, y] = (11, 11, 26)
        canvas.paste(cut, (index * 1024, 0))
    canvas.save(ROOT / "preview_j1c.png")


def main():
    base = Image.open(BASE_PATH).convert("RGB")
    state1 = apply_layer(base, add_state1_damage)
    state2 = apply_layer(state1, add_state2_damage)
    state1.save(ROOT / "key_state1.png")
    state2.save(ROOT / "key_state2.png")
    save_preview(base, state1, state2)


if __name__ == "__main__":
    main()

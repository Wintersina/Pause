def q(point):
    return tuple(point)


def poly(draw, points, fill):
    draw.polygon([q(p) for p in points], fill=fill)


def line(draw, points, fill, width=1):
    draw.line([q(p) for p in points], fill=fill, width=max(1, width * 2), joint="curve")


def rect(draw, box, fill):
    draw.rectangle(tuple(box), fill=fill)


def diamond(draw, x, y, r, fill):
    poly(draw, [(x, y - r), (x + r, y), (x, y + r), (x - r, y)], fill)


